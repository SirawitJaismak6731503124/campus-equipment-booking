-- Re-runnable: drops and recreates (bookings first because it references equipment)
DROP TABLE IF EXISTS bookings;
DROP TABLE IF EXISTS equipment;

CREATE TABLE equipment (
  id       TEXT PRIMARY KEY,
  name     TEXT NOT NULL,
  location TEXT NOT NULL
);

CREATE TABLE bookings (
  id            TEXT PRIMARY KEY,                      -- UUID generated by the API
  equipment_id  TEXT NOT NULL REFERENCES equipment(id),
  borrower_name TEXT NOT NULL,
  start_at      TEXT NOT NULL,                         -- ISO 8601 UTC, always 24 chars (toISOString)
  end_at        TEXT NOT NULL,
  purpose       TEXT NOT NULL DEFAULT '',
  created_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  CHECK (start_at < end_at)                            -- last line of defence at DB level
);

-- Overlap lookups filter by equipment then compare times
CREATE INDEX idx_bookings_equipment_time ON bookings(equipment_id, start_at, end_at);

